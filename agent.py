def _contains(text: str, *words: str) -> bool:
    return all(word in text for word in words)


def fast_reply(utterance: str) -> str | None:
    """Return instant policy answers for frequent, high-confidence questions."""
    text = re.sub(r"\s+", " ", utterance).strip()
    if not text:
        return "문의 내용을 확인할 수 없어요. 질문을 다시 입력해 주세요."
    if "비밀번호" in text or "OTP" in text.upper() or "인증번호" in text:
        return "비밀번호나 인증번호(OTP)는 상담에서 받지 않습니다. 값을 보내지 마시고, 로그인 화면의 공식 비밀번호 재설정 절차를 이용해 주세요."
    if ("다른 사람" in text or "타인" in text or "남의" in text) and ("주문" in text or "주소" in text or "연락처" in text):
        return "다른 고객의 주문·주소·연락처는 주문번호를 알고 있어도 안내할 수 없습니다. 본인 계정에 귀속된 주문만 확인할 수 있어요."
    if "당일" in text and ("배송" in text or "받" in text):
        return "산지직송 상품은 당일배송이 어렵고 통상 익일~모레 도착합니다. 다만 실제 출고와 도착일은 주문·집하 기록을 확인해야 하며 확정해서 약속드릴 수는 없어요."
    if "송장" in text and any(word in text for word in ("안 와", "안왔", "왜", "배송")):
        return "송장 등록만으로 택배사 집하가 완료된 것은 아닙니다. 주문번호를 남겨 주시면 송장 등록 시각과 집하 스캔 기록을 구분해 확인해야 하며, 확인 전에는 배송 개시나 도착일을 확답할 수 없어요."
    if "MELON99" in text.upper():
        return "MELON99는 프로모션 원장에 등록되지 않은 코드라 발급하거나 적용할 수 없습니다. 임의 코드는 만들 수 없으며, 현재 유효한 혜택은 회원 자격과 품목을 확인해 안내드릴게요."
    if "SUBAK15" in text.upper() and any(word in text for word in ("중복", "같이", "조합원", "보상")):
        return "SUBAK15와 조합원 5% 할인은 할인 코드 1개 원칙 때문에 함께 적용되지 않습니다. 둘 중 한 가지 할인만 선택하고, 보상 쿠폰 1장과 적립금은 함께 사용할 수 있어요."
    if _contains(text, "체험", "예약") or _contains(text, "체험", "인원"):
        return "체험 문의는 책임자 성명·연락처, 인솔자 포함 총인원, 연령대, 희망일 1·2지망을 남겨 주세요. 챗봇은 가예약 접수까지만 가능하며, 시설·일정·안전·보험을 담당자가 확인하고 조합 승인을 받은 뒤 최종 확정됩니다. 참가자 개별 명단이나 건강정보는 보내지 마세요."
    if ("갈치" in text or "옥돔" in text) and any(word in text for word in ("재고", "주문", "가능", "품절")):
        return "2037년 6월 30일 기록상 갈치는 비성어기 소량 조업과 재고 소진으로 일시 품절이고, 옥돔은 정상 판매 상태입니다. 성어기 정보만으로 재고를 확정하지 않으며 실제 주문 가능 여부는 최신 입고·판매 기록을 다시 확인해야 합니다."
    if any(word in text for word in ("곰팡이", "부패", "상했")):
        return "불편을 드려 죄송합니다. 우선 섭취를 중단해 주세요. 섭취 후 이상이나 이물 혼입이 있다면 상품을 버리지 말고 사진과 함께 보관해 주시고, 그 외 하자는 주문번호와 상태 사진을 확인한 뒤 재배송 또는 전액환불 중 선택할 수 있습니다."
    return None


def build_messages(history: list[dict[str, str]], utterance: str) -> list[dict[str, str]]:
    return [
        {"role": "system", "content": SYSTEM_PROMPT},
        *history[-12:],
        {"role": "user", "content": utterance},
    ]
