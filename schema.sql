-- Run in Supabase Dashboard > SQL Editor. Safe to run again after schema updates.

CREATE TABLE IF NOT EXISTS public.chatbot_sessions (
    user_id TEXT PRIMARY KEY,
    history JSONB NOT NULL DEFAULT '[]'::jsonb,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS chatbot_sessions_updated_at_idx
    ON public.chatbot_sessions (updated_at DESC);

CREATE TABLE IF NOT EXISTS public.mission_evidence (
    evidence_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id TEXT NOT NULL,
    note TEXT NOT NULL,
    village TEXT CHECK (village IS NULL OR village IN ('교동마을', '갯마을', '두 마을')),
    note_type TEXT NOT NULL DEFAULT '현장 메모',
    source_type TEXT NOT NULL DEFAULT '참여자 발언',
    verification_status TEXT NOT NULL DEFAULT '미확인',
    note_hash TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (user_id, note_hash)
);

CREATE INDEX IF NOT EXISTS mission_evidence_user_created_idx
    ON public.mission_evidence (user_id, created_at DESC);

-- Keep app data out of Supabase's public Data API. The Vercel server uses the
-- server-side Postgres connection string, not an anon client key.
ALTER TABLE public.chatbot_sessions ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.mission_evidence ENABLE ROW LEVEL SECURITY;
