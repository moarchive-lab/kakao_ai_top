CREATE TABLE IF NOT EXISTS public.chatbot_sessions (
    user_id TEXT PRIMARY KEY,
    history JSONB NOT NULL DEFAULT '[]'::jsonb,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS chatbot_sessions_updated_at_idx
    ON public.chatbot_sessions (updated_at DESC);

-- Keep app data out of Supabase's public Data API. The Vercel server uses the
-- server-side Postgres connection string, not an anon client key.
ALTER TABLE public.chatbot_sessions ENABLE ROW LEVEL SECURITY;

-- AX work items. A conversation becomes operational only when the user
-- explicitly taps an intake action. Cases and their audit trail are kept out
-- of the public Data API and are accessed through the server-side connection.
CREATE TABLE IF NOT EXISTS public.ax_cases (
    case_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id TEXT NOT NULL UNIQUE,
    user_id TEXT NOT NULL,
    category TEXT NOT NULL CHECK (
        category IN ('SHIPPING', 'QUALITY', 'SAFETY', 'PROMOTION', 'EXPERIENCE', 'PRIVACY', 'GENERAL')
    ),
    title TEXT NOT NULL,
    summary TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'RECEIVED' CHECK (
        status IN ('RECEIVED', 'IN_REVIEW', 'AWAITING_APPROVAL', 'RESOLVED', 'REJECTED', 'CANCELLED')
    ),
    priority TEXT NOT NULL DEFAULT 'NORMAL' CHECK (
        priority IN ('LOW', 'NORMAL', 'HIGH', 'URGENT')
    ),
    assignee_role TEXT NOT NULL,
    requires_approval BOOLEAN NOT NULL DEFAULT FALSE,
    missing_fields JSONB NOT NULL DEFAULT '[]'::jsonb,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS ax_cases_user_created_idx
    ON public.ax_cases (user_id, created_at DESC);
CREATE INDEX IF NOT EXISTS ax_cases_queue_idx
    ON public.ax_cases (status, priority, created_at ASC);

CREATE TABLE IF NOT EXISTS public.ax_case_events (
    event_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    case_id BIGINT NOT NULL REFERENCES public.ax_cases(case_id) ON DELETE CASCADE,
    event_type TEXT NOT NULL,
    detail JSONB NOT NULL DEFAULT '{}'::jsonb,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS ax_case_events_case_idx
    ON public.ax_case_events (case_id, created_at ASC);

CREATE TABLE IF NOT EXISTS public.ax_approvals (
    approval_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    case_id BIGINT NOT NULL REFERENCES public.ax_cases(case_id) ON DELETE CASCADE,
    approver_role TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'PENDING' CHECK (
        status IN ('PENDING', 'APPROVED', 'REJECTED')
    ),
    reason TEXT,
    decided_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS ax_approvals_pending_idx
    ON public.ax_approvals (status, created_at ASC);

ALTER TABLE public.ax_cases ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.ax_case_events ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.ax_approvals ENABLE ROW LEVEL SECURITY;
